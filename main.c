/*
Найти суммарную площадь для N равнобедренных треугольников,
имеющих одинаковое основание A, но различные длины боковых сторон,
образующие прогрессию A + 1, A + 2, A + 3, ..., A + N.
*/
#include <stdio.h>
#include <math.h>
#include <locale.h>

int main()
{
    setlocale(LC_ALL,"");

    float A,b,h,S,Sn = 0;
    int N, i;

    printf("--------------------------------------------------------------------");

    do {
        printf("\nВведите количество треугольников N: ");
        scanf("%d", &N);scanf("%*[^\n]");
        if (N <= 0 || N >= 100){
            printf("\n====================================================================");
            printf("\n_____________Ошибка:нарушен диапазон входных данных_________________\n");
            printf("====================================================================\n");
        }
    } while (N <= 0 || N >= 100);

    do {
    printf("\nВведите длину основания A: ");
    scanf("%f", &A);scanf("%*[^\n]");
    if (A <= 0 || A >= 100){
        printf("\n====================================================================");
            printf("\n_____________Ошибка:нарушен диапазон входных данных_________________\n");
            printf("====================================================================\n");
    }
    } while (A <= 0 || A >= 100);

    printf("--------------------------------------------------------------------");


    printf("\nВведено количество треугольников N: %2d \n", N);
    printf("Введено длину основания A: %6.3f \n", A);

    printf(" _________________________");
    printf("\n|  N | Бок.стр.| Площадь  |");
    printf("\n ----+---------+----------");
    for (i = 1;i <= N;i ++){
        b = A + i;
        h = sqrt(pow(b,2) - pow(A/2,2));
        S = A * h / 2;
        Sn += S;
        printf("\n| %2d | %7.3f | %8.3f |", i,b,S);
    }
    printf("\n ==== ========= ==========\n");
    printf("\n====================================================================");
    printf("\n\tСуммарная площадь всех треугольников: %10.3f\n", Sn);
    printf("====================================================================\n");

    return 0;
}
